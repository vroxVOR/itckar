export type MessageKey = keyof (typeof messages)["cs"];

export function normalizeLocale(l: string | null | undefined): Locale {
  return (LOCALES as string[]).includes(l ?? "") ? (l as Locale) : "cs";
}

export function t(locale: string | null | undefined, key: MessageKey): string {
  const l = normalizeLocale(locale);
  return messages[l][key] ?? messages.cs[key] ?? key;
}

export function bookingErrorMessage(locale: string, code: string): string {
  const map: Record<string, MessageKey> = {
    slot_busy: "err_slot_busy",
    conflict: "err_slot_busy",
    slot_unavailable: "err_slot_unavailable",
    too_soon: "err_too_soon",
    too_far: "err_too_far",
    cancel_window_passed: "err_cancel_window",
    hold_expired: "err_hold_expired",
  };
  return t(locale, map[code] ?? "error_generic");
}
